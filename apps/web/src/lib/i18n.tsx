interface I18nContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: string) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function isLanguage(value: unknown): value is Language {
  return value === 'nl' || value === 'en' || value === 'fr' || value === 'de'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en')

  useEffect(() => {
    if (!supabase) return

    let active = true
    let requestId = 0

    async function loadLanguage(userId: string | null) {
      const currentRequest = ++requestId

      if (!userId) {
        if (active) setLanguageState('en')
        return
      }

      const { data, error } = await supabase!
        .from('profiles')
        .select('language')
        .eq('id', userId)
        .maybeSingle()

      if (!active || currentRequest !== requestId) return

      if (error || !data || !isLanguage(data.language)) {
        setLanguageState('en')
        return
      }

      setLanguageState(data.language)
    }

    void supabase.auth.getSession().then(({ data }) => {
      if (active) void loadLanguage(data.session?.user.id ?? null)
    })

    const { data } = supabase.auth.onAuthStateChange((_event, session) => {
      queueMicrotask(() => {
        if (active) void loadLanguage(session?.user.id ?? null)
      })
    })

    return () => {
      active = false
      requestId++
      data.subscription.unsubscribe()
    }
  }, [])

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next)
  }, [])

  const t = useCallback((key: string) => {
    return translations[language][key] ?? translations.en[key] ?? key
  }, [language])

  return (
    <I18nContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) {
    throw new Error('useI18n must be used inside I18nProvider.')
  }
  return context
}

export function translateCategory(category: string, t: (key: string) => string) {
  const categories: Record<string, string> = {
    Shirts: 'Shirts',
    'T-shirts': 'T-shirts',
    'Polo shirts': 'Polo shirts',
    Sweaters: 'Sweaters',
    Knitwear: 'Sweaters',
    Trousers: 'Trousers',
    Outerwear: 'Outerwear',
    Shoes: 'Shoes',
    Accessories: 'Accessories',
  }

  return t(categories[category] ?? category)
}
